create table products
(
    pro_id               bigint auto_increment
        primary key,
    product_id           bigint                                    null,
    language_id          int           default 1                   not null,
    company_id           bigint                                    null,
    warehouse_user_id    bigint                                    null,
    sku                  varchar(255)                              null,
    name                 varchar(255)                              null,
    sale_price           double(16, 2)                             not null,
    category_id          varchar(255)                              null comment 'PK of categories',
    barcode              varchar(255)                              null,
    barcode_images       varchar(255)                              null,
    tags                 text                                      null,
    descriptions         text                                      null,
    unit_type            varchar(50)                               null,
    stock                double(8, 2)  default 0.00                not null,
    minimum_stock        double(8, 2)  default 1.00                not null,
    notify_minimum_stock tinyint(3)    default 1                   not null comment '1-Yes 0-No',
    currency_type        varchar(255)                              null,
    fob_price            double(8, 2)                              not null,
    purchase_price       double(8, 2)                              not null,
    locations            varchar(255)                              null,
    created_by           varchar(255)                              null,
    created_on           datetime                                  null,
    modified_on          timestamp     default current_timestamp() not null on update current_timestamp(),
    status               tinyint(3)                                not null comment '0-InActive 1-Active',
    Img                  longblob                                  null,
    imgURL               longtext                                  null,
    simgURL              longtext                                  null,
    id_kor               bigint                                    null,
    cat_id               longtext                                  null,
    cats_id              longtext                                  null,
    sell_with_inventory  int           default 0                   null,
    image_updated        int           default 0                   null,
    price_reduced        double(16, 2) default 0.00                not null,
    sem_red_hasta        int                                       null,
    sem_amarillo_desde   int                                       null,
    sem_amarillo_hasta   int                                       null,
    sem_verde_desde      int                                       null,
    sem_verde_hasta      int                                       null,
    constraint company_id_sku
        unique (sku, company_id)
);

