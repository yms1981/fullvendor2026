create table bakorder_details
(
    detail_id          bigint(19) auto_increment
        primary key,
    order_id           bigint(19)                                not null comment 'PK of orders',
    product_id         bigint(19)                                not null comment 'PK of products',
    qty                double(8, 2)  default 0.00                not null,
    delivered_quantity double                                    not null,
    discount           float                                     not null,
    discount_type      tinyint(3)    default 1                   not null comment '1 = in %, 2 = in $',
    sale_price         double(16, 2) default 0.00                not null,
    fob_price          double(8, 2)  default 0.00                not null,
    sale_price_app     double(16, 2) default 0.00                not null,
    purchase_price     double(8, 2)  default 0.00                not null,
    comment            text                                      not null,
    created            timestamp     default current_timestamp() not null on update current_timestamp(),
    id_kor             bigint(19)                                not null,
    comments           text                                      not null,
    modify_date        timestamp                                 null,
    fixed_pricedate    timestamp                                 null,
    amount_sales       double        default 0                   null,
    discount_amount    double        default 0                   null,
    total_amount       double        default 0                   null,
    amount_delivered   double        default 0                   null,
    discount_delivered double        default 0                   null,
    total_delivered    double        default 0                   null,
    amount             double        default 0                   null,
    discountt          double        default 0                   null,
    delivered_date     timestamp                                 null,
    total              double        default 0                   null,
    groupcustomer      varchar(200)                              null,
    tipolista          varchar(200)                              null,
    perc_price         double(16, 2)                             null,
    salesp             double(16, 2)                             null,
    impprice           double(16, 2)                             null,
    totalprice         double(16, 2)                             null,
    import_price       double(16, 2) default 0.00                null,
    pack               double        default 0                   null,
    delivered_pack     double                                    null,
    company_id         int(10)       default 0                   null,
    constraint odetails
        unique (order_id, product_id)
);

