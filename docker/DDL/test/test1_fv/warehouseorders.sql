    total_amount          double                                null,
    amount_delivered      double                                null,
    discount_delivered    double                                null,
    total_delivered       double                                null,
    name_status_spanish   varchar(255) charset latin1           null,
    name_status_english   varchar(255) charset latin1           null,
    color                 varchar(255) charset latin1           null,
    warehouse_name        varchar(511) charset latin1           null
