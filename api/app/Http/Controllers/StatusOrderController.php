    /**
     * Listado plano: SELECT * FROM status_orders, únicos por cod_status (un registro por estado).
     * Sin relaciones. Id de referencia: cod_status.
     */
    public function listAll()
    {
        $rows = DB::table('status_orders')
            ->orderBy('id_status')
            ->get();
        // Únicos por cod_status: primera ocurrencia de cada cod_status (evita repetir New, Pending, Rejected, etc.)
        $byCodStatus = [];
        foreach ($rows as $row) {
            if (!isset($row->cod_status)) {
                continue;
            }
            $key = (int) $row->cod_status;
            if (!array_key_exists($key, $byCodStatus)) {
                $byCodStatus[$key] = $row;
            }
        }
        ksort($byCodStatus, SORT_NUMERIC);
        return array_values($byCodStatus);
    }

