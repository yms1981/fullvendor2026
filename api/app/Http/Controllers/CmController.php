    public function show($cm)
    {
        $key = is_string($cm) ? trim($cm) : (string) $cm;
        if ($key === '') {
            abort(404);
        }

        if (ctype_digit($key)) {
            $page = Cm::query()->where('pageId', (int) $key)->first();
        } else {
            $page = Cm::query()->where('link', $key)->first();
            // Compatibilidad: aceptar con o sin barra inicial (/about-us).
            if ($page === null && $key[0] !== '/') {
                $page = Cm::query()->where('link', '/' . $key)->first();
            }
            if ($page === null && str_starts_with($key, '/')) {
                $page = Cm::query()->where('link', ltrim($key, '/'))->first();
            }
        }

        if ($page === null) {
            abort(404);
        }

        return $page;
    }

