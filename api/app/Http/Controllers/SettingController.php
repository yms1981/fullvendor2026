    /**
     * Branding público (favicon, logo, título) para pantallas de login del MVC sin autenticación.
     */
    public function publicBranding()
    {
        $setting = Setting::query()->where('settingId', 1)->first();

        if ($setting === null) {
            return response()->json([
                'favicon' => null,
                'logo' => null,
                'title' => '',
                'facebook' => null,
                'twitter' => null,
                'linkedin' => null,
                'instagram' => null,
                'address' => null,
                'phone' => null,
                'email' => null,
            ]);
        }

        return response()->json([
            'favicon' => $setting->favicon,
            'logo' => $setting->logo,
            'title' => $setting->title,
            'facebook' => $setting->facebook,
            'twitter' => $setting->twitter,
            'linkedin' => $setting->linkedin,
            'instagram' => $setting->instagram,
            'address' => $setting->address,
            'phone' => $setting->phone,
            'email' => $setting->email,
        ]);
    }

