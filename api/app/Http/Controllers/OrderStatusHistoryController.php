    public function historyOrderStatus($orderId)
    {
        $statusLang = \request()->get('statusLang')??'eng';
        if($statusLang=='spa') $statusLang='name_status_spanish';
        if($statusLang=='eng') $statusLang='name_status_english';

        $query = DB::table('order_status_history as h')
            ->join('status_orders as s', 'h.cod_status', '=', 's.cod_status')
            ->join('companies as c', 'c.company_id', '=', 'h.user_id')
            ->select(
                'h.*',
                DB::raw("s.$statusLang as name_status"), // Sustituye $name por tu columna real
                's.color',
                'h.created_at',
                'c.email as user',
                'c.short_name as user_name'
            )
            ->where('h.order_id', $orderId)
            ->orderByDesc('h.history_id');

        // Ejecutar la consulta y obtener resultados
        $result = $query->get();

        // Retornar los datos como JSON
        return response()->json([
            'history' => $result,
        ]);

    }

